-- Application-owned landing/checkpoint setup only. Terraform provisions MARKET,
-- RAW, the storage integration, file format and external stages first.
-- This is not an infrastructure deployment script. See ../terraform/README.md.
-- Use the configured ingestion role; no administrative role switch is required.
USE DATABASE MARKET;
USE SCHEMA RAW;
-- Fail before any setup DDL if an existing environment still needs migration.
EXECUTE IMMEDIATE $$
DECLARE
    migration_required EXCEPTION (-20001, 'Run python -m scripts.migrate_ingestion_metadata before ingestion setup.');
BEGIN
    IF (EXISTS(SELECT 1 FROM MARKET.INFORMATION_SCHEMA.TABLES
        WHERE TABLE_SCHEMA='RAW' AND TABLE_NAME IN ('REFERENCE_MANIFEST','PRICE_REFRESH_MANIFEST'))) THEN
        RAISE migration_required;
    END IF;
END;
$$;
CREATE SCHEMA IF NOT EXISTS ADMIN;

CREATE TABLE IF NOT EXISTS RAW.DAILY_STOCKS_RAW (
    API_DATE DATE,
    RUN_ID STRING,
    SOURCE STRING,
    RAW_PAYLOAD STRING,
    INGESTED_AT TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS MARKET.ADMIN.INGESTION_CHECKPOINTS (
    RUN_ID STRING,
    API_DATE DATE,
    STATUS STRING,
    TOTAL_TICKERS INT,
    ROWS_INSERTED INT,
    STARTED_AT TIMESTAMP_NTZ,
    COMPLETED_AT TIMESTAMP_NTZ,
    ERROR_MESSAGE STRING,
    S3_BUCKET STRING,
    S3_KEY STRING,
    S3_ETAG STRING,
    S3_SHA256 STRING
);

ALTER TABLE MARKET.ADMIN.INGESTION_CHECKPOINTS
    ADD COLUMN IF NOT EXISTS S3_BUCKET STRING;
ALTER TABLE MARKET.ADMIN.INGESTION_CHECKPOINTS
    ADD COLUMN IF NOT EXISTS S3_KEY STRING;
ALTER TABLE MARKET.ADMIN.INGESTION_CHECKPOINTS
    ADD COLUMN IF NOT EXISTS S3_ETAG STRING;
ALTER TABLE MARKET.ADMIN.INGESTION_CHECKPOINTS
    ADD COLUMN IF NOT EXISTS S3_SHA256 STRING;

CREATE TABLE IF NOT EXISTS MARKET.ADMIN.REFERENCE_MANIFEST (
    API_DATE DATE, SOURCE STRING, RUN_ID STRING, ROW_COUNT INTEGER,
    REQUESTED_COUNT INTEGER, S3_KEY STRING, SHA256 STRING, COMPLETED_AT TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS MARKET.ADMIN.PRICE_REFRESH_MANIFEST (
    CAMPAIGN STRING, API_DATE DATE, S3_KEY STRING, SHA256 STRING, REFRESHED_AT TIMESTAMP_NTZ
);
